"""空窗策略戳（主链模块，非空桩）。

空窗处置成功必须**同票**写策略戳，之后对该区间的补扫只能按架构吃戳：
已戳区间冻结——禁止再次创建或删除空窗行，补扫只能校验戳。

架构取舍（全局只贯彻一种）：
    **戳冻结区间**——戳一旦写入，该区间的空窗行集合（有/无零窗行）与戳世代即冻结；
    补扫只能核验，不得按现行策略重写，也不得删行。

戳载荷（同一条 INSERT，随处置同一事务）：
- 策略码：发射零窗 / 跳过空窗（空窗处置实际执行的口径）；
- 跨越区间：`房间键|首个缺口窗起~末个缺口窗止`；
- 窗键清单：本次处置覆盖的全部空窗键（跳过口径下即「跳过证明」——这些键经扫描确认无事件且不物化）；
- 戳号：全局唯一戳标识；
- 世代：本架构下恒为 1（戳冻结，永不自增）。

硬约束（fail-closed）：
- 禁止策略执行成功戳空：窗键清单为空禁止写戳；零窗行不得无戳；
- 禁止戳=跳过却再物化零窗行；
- 禁止戳=发射零窗却被补扫删行；
- 半截失败整票回滚：打戳与物化/跳过判定同处调用方事务，任一步异常整体回滚。
"""

import json
import uuid

from app.modules.空窗发射策略 import 发射零窗, 跳过空窗
from app.seed import 此刻

状态 = "已实现"

口径 = "戳冻结区间"
冻结 = True
可补扫改写 = False
世代基准 = 1


class 空窗策略戳错误(RuntimeError):
    """策略戳缺失/冲突/漂移：fail-closed，调用方须整票回滚或拒绝补扫改写。"""


def _全部戳(conn) -> list[dict]:
    rows = conn.execute("SELECT * FROM 空窗策略戳 ORDER BY 编号").fetchall()
    out = []
    for r in rows:
        d = dict(r)
        try:
            d["窗键清单"] = list(json.loads(d["窗键清单"] or "[]"))
        except Exception:
            d["窗键清单"] = []
        d.setdefault("世代", 世代基准)
        out.append(d)
    return out


def 区间键(房间键: str, 空窗们: list[dict]) -> str:
    """跨越区间 = 房间键|首缺口窗起~末缺口窗止（空窗们须按窗起升序）。"""
    if not 空窗们:
        raise 空窗策略戳错误("禁止戳空：无缺口窗可组成跨越区间")
    首, 末 = 空窗们[0], 空窗们[-1]
    return f"{房间键}|{首['窗起']}~{末['窗止']}"


def 窗键戳(conn, 窗键: str) -> dict | None:
    """找覆盖该窗键的策略戳；无则 None。窗键清单是覆盖裁决的权威依据。"""
    for 戳 in _全部戳(conn):
        if 窗键 in 戳["窗键清单"]:
            return 戳
    return None


def 应冻结补扫(conn, 窗键: str) -> bool:
    """该窗键是否已被戳；已戳则补扫必须冻结（只校验，不改写）。"""
    return 窗键戳(conn, 窗键) is not None


def 已戳窗键集(conn, 房间键: str) -> dict[str, dict]:
    """该房全部已戳窗键 → 戳行。"""
    前缀 = f"{房间键}|"
    out = {}
    for 戳 in _全部戳(conn):
        for wk in 戳["窗键清单"]:
            if wk.startswith(前缀):
                out[wk] = 戳
    return out


def 窗键到戳号(conn) -> dict[str, str]:
    return {wk: 戳["戳号"] for 戳 in _全部戳(conn) for wk in 戳["窗键清单"]}


def 尝试打戳(conn, *, 房间键: str, 策略码: str, 空窗们: list[dict], 处理时: str = "") -> dict:
    """同票写策略戳。**调用方须处于写事务内**；失败即抛错由调用方整体回滚。

    - 窗键清单为空 → 抛错（禁止策略执行成功戳空）；
    - 任一窗键已被戳 → 抛错（戳冻结区间，禁止重复打戳/改写世代）；
    - 世代恒为 1（本架构不按补扫世代覆盖）。
    """
    if 策略码 not in (发射零窗, 跳过空窗):
        raise 空窗策略戳错误(f"非法策略码:{策略码 or '空'}，禁止打戳")
    if not 空窗们:
        raise 空窗策略戳错误("禁止策略执行成功戳空：本次处置无缺口窗可戳")
    窗键清单 = [空["窗键"] for 空 in 空窗们]
    for wk in 窗键清单:
        旧 = 窗键戳(conn, wk)
        if 旧:
            raise 空窗策略戳错误(
                f"窗键{wk}已被戳{旧['戳号']}冻结，禁止重复打戳或改写世代"
            )
    区间 = 区间键(房间键, 空窗们)
    戳号 = f"戳-{房间键}-{空窗们[0]['窗起']}-{uuid.uuid4().hex[:10]}"
    conn.execute(
        """INSERT INTO 空窗策略戳(策略码,跨越区间,窗键清单,戳号,时刻,世代)
           VALUES (?,?,?,?,?,?)""",
        (策略码, 区间, json.dumps(窗键清单, ensure_ascii=False), 戳号, 处理时 or 此刻(), 世代基准),
    )
    return {
        "策略码": 策略码,
        "跨越区间": 区间,
        "窗键清单": 窗键清单,
        "戳号": 戳号,
        "世代": 世代基准,
    }


def 校验戳对窗(conn, 戳: dict, 窗键: str) -> None:
    """在已戳区间内对单个窗键做只读核验；漂移即抛错（补扫不得改写/删行）。"""
    行 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (窗键,)).fetchone()
    if 戳["策略码"] == 发射零窗:
        if not 行:
            raise 空窗策略戳错误(
                f"戳=发射零窗却缺行:{窗键}（戳号{戳['戳号']}）——禁止补扫删行"
            )
    elif 戳["策略码"] == 跳过空窗:
        if 行 and int(行["空窗"]):
            raise 空窗策略戳错误(
                f"戳=跳过却物化零窗行:{窗键}（戳号{戳['戳号']}）——禁止补扫再物化"
            )
    else:
        raise 空窗策略戳错误(f"戳{戳['戳号']}策略码非法:{戳['策略码'] or '空'}")


def 核证(conn) -> dict:
    """全局只读核证：戳载荷完整、戳与窗行一致、零窗行不无戳。"""
    问题: list[str] = []
    戳们 = _全部戳(conn)
    已戳: dict[str, dict] = {}
    for 戳 in 戳们:
        if not 戳["戳号"]:
            问题.append(f"戳#{戳['编号']}缺戳号（禁止戳空）")
        if 戳["策略码"] not in (发射零窗, 跳过空窗):
            问题.append(f"戳{戳['戳号'] or '#' + str(戳['编号'])}策略码非法:{戳['策略码'] or '空'}")
        if not 戳["跨越区间"]:
            问题.append(f"戳{戳['戳号'] or '#' + str(戳['编号'])}缺跨越区间（禁止戳空）")
        if not 戳["窗键清单"]:
            问题.append(f"戳{戳['戳号'] or '#' + str(戳['编号'])}窗键清单为空（禁止戳空）")
        if int(戳.get("世代") or 0) < 世代基准:
            问题.append(f"戳{戳['戳号'] or '#' + str(戳['编号'])}世代非法:{戳.get('世代')}")
        for wk in 戳["窗键清单"]:
            已戳[wk] = 戳
            行 = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
            if 戳["策略码"] == 发射零窗:
                if not 行:
                    问题.append(f"戳=发射零窗却缺行:{wk}（禁止补扫删行）")
                elif int(行["空窗"]) and 行["空窗策略快照"] != 发射零窗:
                    问题.append(f"零窗{wk}快照非法:{行['空窗策略快照'] or '空'}")
            elif 戳["策略码"] == 跳过空窗:
                if 行 and int(行["空窗"]):
                    问题.append(f"戳=跳过却物化零窗行:{wk}（禁止补扫再物化）")

    for 行 in conn.execute("SELECT * FROM 热度窗 WHERE 空窗=1"):
        if 行["窗键"] not in 已戳:
            问题.append(f"零窗无戳:{行['窗键']}（禁止策略执行成功戳空）")

    return {
        "valid": not 问题,
        "问题": 问题,
        "戳数": len(戳们),
        "冻结区间数": len(戳们),
        "窗键覆盖数": len(已戳),
        "口径": 口径,
        "冻结": 冻结,
        "可补扫改写": 可补扫改写,
    }


def 查策略戳(conn, 区间: str | None = None) -> dict:
    """只读核证接口：列出策略戳并给出核证结论（不写库）。"""
    try:
        戳们 = _全部戳(conn)
        核 = 核证(conn)
    except Exception as e:  # 老库未初始化等
        return {
            "策略戳": [],
            "核证": {"valid": False, "问题": [f"读取策略戳失败：{e}"]},
            "口径": 口径,
            "冻结": 冻结,
            "可补扫改写": 可补扫改写,
        }
    if 区间:
        戳们 = [t for t in 戳们 if t["跨越区间"] == 区间]
    输出 = []
    for 戳 in 戳们:
        d = dict(戳)
        if d["策略码"] == 跳过空窗:
            d["跳过证明"] = {
                "窗键数": len(d["窗键清单"]),
                "窗键": list(d["窗键清单"]),
                "说明": "扫描确认这些窗无事件且按跳过口径不物化，戳冻结该结论",
            }
        else:
            d["跳过证明"] = None
        输出.append(d)
    return {
        "策略戳": 输出,
        "核证": 核,
        "口径": 口径,
        "冻结": 冻结,
        "可补扫改写": 可补扫改写,
    }
