"""空窗发射策略（主链模块，非空桩）。

当事件时水位越过某窗窗止而该窗无任何事件时，按全局唯一选定的策略处理空窗。
全局只贯彻一种口径，由站规「空窗发射策略」给出，取值二选一：

- 发射零窗：无事件也关闭并物化零赞/零送/零笔数的发射行（空窗=1，带策略快照）；
- 跳过空窗：无事件不创建窗行；水位推进不因此失败；跳过策略下严禁物化零窗行冒充发射。

硬约束：
- 关窗扫描完整性——每个被水位越过窗止的窗都必须按站规有交代，不得有的关、有的跳过而无站规；
- 失败闭——策略未定（站规缺失/空值/未知名）时禁止发射，由调用方整体回滚，不得半截创建空窗；
- 历史不暗改——已发射的历史零窗行带「空窗策略快照」，策略切换后其命运不随之改变；
- 跳过策略下出现任何空窗=1 的行，即视为冒充发射，只读接口判 invalid。
"""

from app.services import 时间

状态 = "已实现"

发射零窗 = "发射零窗"
跳过空窗 = "跳过空窗"
策略键 = "空窗发射策略"
合法策略 = (发射零窗, 跳过空窗)

枚举上限 = 10000  


class 策略未定错误(RuntimeError):
    """失败闭：站规未给出合法空窗策略，禁止发射。"""


def 取策略(conn) -> str | None:
    """读当前全局策略；未配置/空值/未知名一律返回 None（调用方须失败闭，不得猜默认）。"""
    row = conn.execute("SELECT 值 FROM 站规 WHERE 键=?", (策略键,)).fetchone()
    if not row:
        return None
    值 = (row["值"] or "").strip()
    return 值 if 值 in 合法策略 else None


def 解析窗键(窗键: str) -> tuple[str, str]:
    房间键, _, 窗起 = 窗键.partition("|")
    return 房间键, 窗起


def 枚举越过窗止的空窗(conn, 房间键: str, 水位事件时: str, 窗长秒: int) -> list[dict]:
    """枚举该房「窗止已被水位越过、且热度窗表里不存在行」的全部窗（按窗起升序）。

    扫描完整性的根基：不是只关已物化的窗，而是从开播事件时起逐窗对齐枚举，
    保证水位跳跃跨过无事件区间时每个空窗都被看见并交给当前策略处置。
    """
    房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()
    if not 房:
        return []
    开播 = 时间.对齐窗起(房["开播事件时"], 窗长秒)
    水位 = 时间.解析(水位事件时)
    窗长 = 窗长秒
    候选 = []
    窗起dt = 时间.解析(开播)
    for i in range(枚举上限):
        窗起 = 时间.格式(窗起dt)
        窗止 = 时间.窗止(窗起, 窗长)
        if not (水位 >= 时间.解析(窗止)):
            break  
        窗键 = 时间.窗键(房间键, 窗起)
        if not conn.execute("SELECT 1 FROM 热度窗 WHERE 窗键=?", (窗键,)).fetchone():
            候选.append({"窗键": 窗键, "窗起": 窗起, "窗止": 窗止})
        窗起dt = 时间.解析(窗止)
    else:
        
        raise RuntimeError(
            f"房间{房间键}空窗枚举触顶{枚举上限}（水位{水位事件时}异常超前），拒绝不完整扫描"
        )
    return 候选


def 窗行是否合法(窗行, 当前策略: str | None) -> tuple[bool, str]:
    """判一行已物化热度窗在当前策略下是否合法（历史零窗不随切换被暗改）。"""
    if not 窗行:
        return False, "窗行不存在"
    if not int(窗行["空窗"]):
        return True, "事件窗"
    快照 = 窗行["空窗策略快照"]
    if 快照 != 发射零窗:
        return False, f"空窗行策略快照非法:{快照 or '空'}——跳过策略下物化零窗属冒充发射"
    if 当前策略 == 跳过空窗:
        
        return True, "历史零窗（发射零窗时期发射，策略切换不暗改）"
    return True, "发射零窗"


def 缺失窗是否合法(当前策略: str | None) -> tuple[bool, str]:
    """判一个「窗止已越过但无窗行」的缺口在当前策略下是否合法。"""
    if 当前策略 == 跳过空窗:
        return True, "跳过空窗：无事件不物化窗行"
    if 当前策略 == 发射零窗:
        return False, "发射零窗策略下越窗止空窗必须有零窗关闭行"
    return False, "策略未定：缺口口径不可判定（失败闭）"
